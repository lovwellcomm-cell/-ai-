"""固定问题集的冻结锚点。

细则第 2 条「完整性」的测试方法是「把问题拆成子问题，检查每个子问题是否都有答案」。
拆子问题是判断题，代码做不了 —— 所以这里**由人把 6 道固定题的骨架写死**，
机器只负责检查骨架在不在。这是整个标准里唯一一处人工判断，刻意放在单独的文件里，
方便直接改。

## 它是下限，不是度量

实测这组锚点横跨 5 组配置（回答长度相差 24 倍，从 386 到 9326 个 completion token）
**全部 5/5 通过**。意思是：它永远不会骗人，但也**分辨不出好坏**。
它只能回答「这个回答有没有把该说的数说了」，回答不了「说得好不好」。
所以它按逐题打勾呈现，绝不折算成分数。

## 哪几道题能锚、哪几道不能（实测结论）

| 题 | 能锚住什么 | 锚不住什么 |
|---|---|---|
| 简单 | 一个数值，全部可查 | — |
| 追问-1 | 两个数值，全部可查 | — |
| 趋势 | 3 年 × 2 个指标的骨架 | 「趋势判断得对不对」 |
| 跨表 | 4 个数值 | 「这个差异说明了什么」 |
| 覆盖 | 提到了毛利率 + (给了原因 或 明确说了未披露) | 「归因是否正确」 |
| 追问-2 | 只锚得住「提到了 2024 且给了数」 | **它真正考的那件事锚不住** |

追问-2 是「那去年呢？」—— 问题本身故意歧义，5 组回答采取了三种互不兼容的策略
（有的倒出 10 项报告，有的给主要会计数据，有的给资产处置收益）。任何锚点都等于
把其中一种判成"对"，而「**它有没有偷偷替用户猜一个指代**」这件事机器判不了，只能人读。
"""

# spec 是「任一条正则命中即算通过」；写成 {"min_numbers": n} 表示「回答里至少 n 个数字」
ANCHORS = {
    "趋势": [
        ("营业收入2023", [r"179\.06", r"17,905,865,235\.94"]),
        ("营业收入2024", [r"223\.23", r"22,322,579,930\.98"]),
        ("营业收入2025", [r"246\.74", r"24,673,670,269\.16"]),
        ("归母净利润2023", [r"4\.26亿", r"426,452,861\.87"]),
        ("归母净利润2024", [r"5\.62亿", r"561,708,879\.75"]),
        ("归母净利润2025", [r"5\.99亿", r"599,143,119\.39"]),
        ("趋势判断", [r"放缓", r"低于", r"回落", r"增速.{0,6}(下降|回落|放缓)"]),
    ],
    "跨表": [
        ("本期经营现金流净额", [r"24\.75", r"2,475,082,817\.33"]),
        ("本期净利润", [r"6\.23", r"622,525,281\.91"]),
        ("上期经营现金流净额", [r"-5\.89", r"-589,153,155\.66"]),
        ("上期净利润", [r"5\.77亿", r"576,965,894\.85"]),
        ("差异归因线索", [r"回款", r"非付现", r"减值", r"折旧", r"调节"]),
    ],
    "覆盖": [
        ("提到毛利率", [r"毛利率"]),
        ("收入成本变动幅度", [r"10\.64", r"10\.80"]),
        # 这道题的真实答案是"年报没单独披露毛利率变动原因"，
        # 所以锚点必须同时接受「给了原因」和「明确说没披露」两种正确回答
        ("原因或明确未披露", [r"原材料价格", r"未(单独)?披露", r"未.{0,8}(说明|解释)", r"未明确"]),
    ],
    "简单": [
        # 合并口径是主答案；母公司口径（5.43 亿元）也算对，
        # 但那种情况必须注明口径 —— 那条由 eval_rubric.caliber() 单独管
        ("营业收入数值", [r"246\.74", r"24,673,670,269\.16", r"5\.43亿", r"543,313,191\.06"]),
    ],
    "追问-1": [
        ("营业收入", [r"246\.74", r"24,673,670,269\.16"]),
        ("归母净利润", [r"5\.99", r"599,143,119\.39"]),
    ],
    "追问-2": [
        ("提到2024", [r"2024"]),
        ("给出至少三个数字", {"min_numbers": 3}),
    ],
}


def anchors(tag: str, answer: str) -> dict:
    """逐题检查锚点。返回逐项清单，不折算成分数。"""
    import re

    from tools.eval_rubric import _norm

    specs = ANCHORS.get(tag)
    if not specs:
        return {"锚点": [], "锚点全中": None}

    text = _norm(answer)
    n_numbers = len(re.findall(r"\d[\d,]*\.?\d*", answer or ""))
    detail = []
    for name, spec in specs:
        if isinstance(spec, dict):
            ok = n_numbers >= spec.get("min_numbers", 0)
        else:
            ok = any(re.search(p, text) for p in spec)
        detail.append({"项": name, "中": ok})
    return {"锚点": detail, "锚点全中": all(d["中"] for d in detail)}
